CREATE OR REPLACE VIEW VIEW_BOLT_MOV_CONTASRECEBER AS
SELECT 15 AS DIAS,
       TO_CHAR(SUM(NVL(DECODE(P.CODCOB, '237', P.VALOR, 0), 0)),
               '999G999G990D00') AS "237",
       TO_CHAR(SUM(NVL(DECODE(P.CODCOB, 'C', P.VALOR, 0), 0)),
               '999G999G990D00') AS "C"
  FROM PCPREST P, PCCLIENT C
 WHERE P.CODCLI = C.CODCLI
   AND P.DTPAG IS NULL
   AND P.CODCOB IN ('237', 'C')
   AND P.DTVENC <= TRUNC(SYSDATE + 15)
UNION
SELECT 30 AS DIAS,
       TO_CHAR(SUM(NVL(DECODE(P.CODCOB, '237', P.VALOR, 0), 0)),
               '999G999G990D00') AS "237",
       TO_CHAR(SUM(NVL(DECODE(P.CODCOB, 'C', P.VALOR, 0), 0)),
               '999G999G990D00') AS "C"
