   AND P.DTPAG IS NULL
   AND P.CODCOB IN ('237', 'C')
   AND P.DTVENC > TRUNC(SYSDATE + 30)
   AND P.DTVENC <= TRUNC(SYSDATE + 45)
UNION
SELECT 60 AS DIAS,
       TO_CHAR(SUM(NVL(DECODE(P.CODCOB, '237', P.VALOR, 0), 0)),
               '999G999G990D00') AS "237",
