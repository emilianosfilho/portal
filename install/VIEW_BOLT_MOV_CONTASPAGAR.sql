CREATE OR REPLACE VIEW VIEW_BOLT_MOV_CONTASPAGAR AS
SELECT 15 AS DIAS, TO_CHAR(NVL(SUM(VALOR),0),'999G999G990D00') AS VALOR
FROM PCLANC
WHERE DTPAGTO IS NULL
AND DTVENC <= TRUNC(SYSDATE+15)
UNION
SELECT 30 AS DIAS, TO_CHAR(NVL(SUM(VALOR),0),'999G999G990D00') AS VALOR
FROM PCLANC
WHERE DTPAGTO IS NULL
AND DTVENC > TRUNC(SYSDATE+15)
AND DTVENC <= TRUNC(SYSDATE+30)
UNION
SELECT 45 AS DIAS, TO_CHAR(NVL(SUM(VALOR),0),'999G999G990D00') AS VALOR
FROM PCLANC
WHERE DTPAGTO IS NULL
AND DTVENC > TRUNC(SYSDATE+30)
AND DTVENC <= TRUNC(SYSDATE+45)
UNION
SELECT 60 AS DIAS, TO_CHAR(NVL(SUM(VALOR),0),'999G999G990D00') AS VALOR
FROM PCLANC
WHERE DTPAGTO IS NULL
AND DTVENC > TRUNC(SYSDATE+45)
AND DTVENC <= TRUNC(SYSDATE+60)
UNION
SELECT 90 AS DIAS, TO_CHAR(NVL(SUM(VALOR),0),'999G999G990D00') AS VALOR
FROM PCLANC
WHERE DTPAGTO IS NULL
AND DTVENC > TRUNC(SYSDATE+60)
AND DTVENC <= TRUNC(SYSDATE+90)
UNION
SELECT 120 AS DIAS, TO_CHAR(NVL(SUM(VALOR),0),'999G999G990D00') AS VALOR
FROM PCLANC
WHERE DTPAGTO IS NULL
AND DTVENC > TRUNC(SYSDATE+90)
AND DTVENC <= TRUNC(SYSDATE+120);
